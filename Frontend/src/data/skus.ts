export function getSkuTotalStock(sku: Sku): number {
  const s = sku.stock
  return s.indiaAvailable + s.indiaPacked + s.inTransit + s.usaAvailable + s.usaReserved + s.fba
}

export function getDaysOfCover(sku: Sku): number {
  const available = sku.stock.usaAvailable + sku.stock.indiaAvailable
  return Math.round(available / 1.8)
}
